#!/usr/bin/env python3
"""Generate iPhone/StepX bindings from the common G1 schema; --check is read-only."""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "shared/agent_protocol/schema.json"


def swift_type(schema):
    if "$ref" in schema:
        return "APT" + schema["$ref"].split("/")[-1]
    if "anyOf" in schema:
        return swift_type(schema["anyOf"][0]) + "?"
    kind = schema.get("type", "string")
    if kind == "array":
        return "[" + swift_type(schema["items"]) + "]"
    return {"string": "String", "integer": "Int64", "boolean": "Bool", "object": "[String: APTJSONValue]"}.get(kind, "APTJSONValue")


def ts_type(schema):
    if "$ref" in schema:
        return "APT" + schema["$ref"].split("/")[-1]
    if "anyOf" in schema:
        return " | ".join(ts_type(s) for s in schema["anyOf"])
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(map(json.dumps, schema["enum"]))
    if schema.get("type") == "array":
        return "ReadonlyArray<" + ts_type(schema["items"]) + ">"
    return {"string": "string", "integer": "number", "boolean": "boolean", "null": "null", "object": "Readonly<Record<string, unknown>>"}.get(schema.get("type"), "unknown")


def outputs():
    raw = SOURCE.read_bytes()
    definitions = json.loads(raw)["$defs"]
    header = "// Generated by scripts/generate_agent_protocol.py; schema SHA256 " + hashlib.sha256(raw).hexdigest() + ".\n"
    swift = header + (ROOT / "shared/agent_protocol/SwiftSupport.swift").read_text() + "\n"
    swift += 'private let aptProtocolSchemaText = #"""\n' + json.dumps(json.loads(raw), ensure_ascii=False, separators=(",", ":")) + '\n"""#\n'
    ts = header
    for name, definition in definitions.items():
        if definition.get("type") == "object" and definition.get("properties"):
            swift += f"struct APT{name}: Codable, APTContractMessage {{\n    static let contractName = \"{name}\"\n"
            ts += f"export interface APT{name} {{\n"
            for field, schema in definition["properties"].items():
                swift += f"    let {field}: {swift_type(schema)}\n"
                ts += f"  readonly {field}: {ts_type(schema)};\n"
            fields = list(definition["properties"])
            swift += "    enum CodingKeys: String, CodingKey { case " + ", ".join(fields) + " }\n"
            swift += "    func encode(to encoder: Encoder) throws {\n        var fields = encoder.container(keyedBy: CodingKeys.self)\n"
            for field in fields:
                swift += f"        try fields.encode({field}, forKey: .{field})\n"
            swift += "    }\n"
            swift += "}\n"
            ts += "}\n"
        elif "enum" in definition:
            swift += f"enum APT{name}: String, Codable {{\n"
            for value in definition["enum"]:
                case = "".join(w.capitalize() if i else w for i, w in enumerate(value.split("_")))
                swift += f'    case {case} = "{value}"\n'
            swift += "}\n"
            ts += f"export type APT{name} = {ts_type(definition)};\n"
        else:
            swift += f"typealias APT{name} = {swift_type(definition)}\n"
            ts += f"export type APT{name} = {ts_type(definition)};\n"
    return {
        ROOT / "ios/GrowthApp/Agent/AgentProtocol.generated.swift": swift,
        ROOT / "stepx-client/src/growth/agent-contract.generated.ts": ts,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, data in outputs().items():
        if args.check:
            if not path.is_file() or path.read_text() != data:
                raise SystemExit("Generated Agent binding is stale: " + str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(data)
    print("Agent bindings match the shared schema" if args.check else "Generated Agent bindings")


if __name__ == "__main__":
    main()
