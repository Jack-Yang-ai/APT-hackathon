import Foundation

/// 「这一场为什么还没有纪要」——**说出原因,不要三种原因一句话**。
///
/// ## 它修的是什么
///
/// `tasks.last_error` 一直在写,而在此之前**没有任何投影读它**:
/// 「云代理还没配」「这一场一块音频都没有」「查询回了看不懂的报文」
/// 在界面上全塌缩成同一句「还没到有纪要的时候」。
///
/// 三种原因对应三种完全不同的动作 —— 去设置里填地址 / 删掉这一场 / 什么都不做地等。
/// 一句话把它们盖住,用户就无从判断自己该做什么,于是什么都不做。
///
/// ## 为什么是纯函数
///
/// 「三种原因给出三种说明」是这条的验收,而验收不能靠人去点三次界面。
/// 文案留在 View 的 `load()` 里就只能靠肉眼验 —— 那正是这一条一开始被漏掉的原因。
enum SessionStallText {

    /// - Parameter word: `TaskQueue.lastWord` 的结果。`nil` = 这一场压根没有任务行
    ///   (比如导入的历史场次),那不是失败,只是还没轮到它。
    static func explain(_ word: (state: String, reason: String?)?) -> String {
        guard let word else {
            return "这一场还没有生效的转写 —— 还没到有纪要的时候。"
        }
        // 「不会自己好」与「还在路上」要分开,和 §4.1.7
        // 「说话人整理中 vs 只保留了文字记录」分的是同一条线。
        if word.state == "dead" || word.state == "degraded" {
            let why = word.reason.map { "原因:\($0)" }
                // 没记原因本身就是缺陷(§3.2:兜底的 except 要么记录要么抛)。
                // 说出来,别拿一句体面话盖过去。
                ?? "任务表里没记原因 —— 那本身是个缺陷,请把这句话反馈出来。"
            return "这一场没能处理完,而且不会自己好了。\n\(why)\n首页长按这张卡可以「再试一次」。"
        }
        if let reason = word.reason, !reason.isEmpty {
            return "还在处理。上一次没成的原因:\(reason)"
        }
        return "这一场还没有生效的转写 —— 还没到有纪要的时候。"
    }
}
