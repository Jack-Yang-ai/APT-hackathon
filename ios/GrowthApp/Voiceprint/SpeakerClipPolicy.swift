import Foundation

/// 说话人代表片段的口径(PRD §4.4.10;2026-08-25 用户拍板「按人存,不按句存」)。
///
/// ⚠️ **这里只有口径,没有裁剪实现** —— 片段由 Mac 裁(见迁移 v30 的注释:
/// Mac 判决时已经算过 `speech_ratio`,手机再算一遍就是第二份实现)。
/// 手机这边做的是**落库与上限**。
enum SpeakerClipPolicy {

    /// 每个说话人留几段。用户原话:「不用全部都存」。
    ///
    /// 上限是 3 而不是 2:认人靠的是「听得出是谁」,一段撞上背景噪音就废了 ——
    /// 留 3 段的成本是每人 ≈12 秒音频(几百 KB),而少一段的成本是认不出人。
    static let maxPerSpeaker = 3

    /// 挑哪几段:**最长、人声占比最高**的那几段(认人时最听得清)。
    /// 排序键由 Mac 给出,手机只按 `speech_ratio` 降序、`duration_ms` 降序取前 N。
    static let minSpeechRatio = 0.6

    /// 🔴 **人命名并 enroll 之后不再新增,已存的照旧能听。**
    ///
    /// 「不再新增」是因为片段的用途只有一个:**认人**。人已经认出来了,
    /// 再攒片段就是纯占空间。而「已存的照旧能听」是因为片段挂在**簇**上,
    /// 匿名人格被命名时改的是 `voiceprint_clusters` 那张映射表,片段一个字都不用动。
    static let stopCollectingAfterEnroll = true
}
